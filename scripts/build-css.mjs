#!/usr/bin/env node
// Builds dist/components.css — every component's CSS contract in one file, inside
// @layer rse.components, so any host style (unlayered) wins without !important.
//
//   node scripts/build-css.mjs          # write
//   node scripts/build-css.mjs --check  # exit 1 if stale
//
// Sources are the components/<group>/<Name>.css files next to each component, in manifest order.
// A component without one still styles itself inline; roadmap P2 moves them over.

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const OUT = 'dist/components.css';
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const manifest = JSON.parse(read('rse.manifest.json'));
const pkg = JSON.parse(read('package.json'));

const sources = manifest.components.map((c) => c.sourcePath.replace(/\.jsx$/, '.css')).filter((p) => existsSync(join(ROOT, p)));
const raw = /#[0-9a-f]{3,8}\b|rgba?\(/i;
for (const p of sources) {
  const css = read(p).replace(/\/\*[\s\S]*?\*\//g, '');
  if (raw.test(css)) { console.error(`${p}: raw colour — use a --rse-color-* token`); process.exit(1); }
}
const body = sources.map((p) => `/* ${p} */\n${read(p).trim()}\n`).join('\n');
const out = `/* GENERATED by scripts/build-css.mjs — do not edit. ${pkg.name}@${pkg.version}
   Component CSS contract. Needs the tokens (tokens/tokens.css) and tokens/base-runtime.css. */
@layer rse.components{
${body}}
`;
const current = existsSync(join(ROOT, OUT)) ? read(OUT) : null;
if (current === out) { console.log(`components.css up to date (${sources.length} components)`); process.exit(0); }
if (checkOnly) { console.log(`${OUT} is out of date — run \`npm run sync\``); process.exit(1); }
mkdirSync(join(ROOT, 'dist'), { recursive: true });
writeFileSync(join(ROOT, OUT), out);
console.log(`wrote ${OUT} (${sources.length} component stylesheets)`);
