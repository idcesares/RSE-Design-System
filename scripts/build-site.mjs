#!/usr/bin/env node
// Builds the reference site: site/index.html and one page per component in site/components/,
// generated from dist/components.json (props, values, classes, tokens, files) and each
// component's .prompt.md (usage). The live example on each page is the showcase demo
// (showcase/demos.js), rendered by site/site.js with the real components from dist/rse.js.
//
//   node scripts/build-site.mjs          # write
//   node scripts/build-site.mjs --check  # exit 1 if stale
//
// The showcase is the overview for leadership and newcomers (pt-BR); this is the reference for
// people building with the system. Like docs/components.md it is system documentation, so its
// chrome is English (AGENTS.md rule 4); demos and glosses are pt-BR and marked lang="pt-BR".
// Opens offline: plain files, no build step, the same vendored React the starters use.

import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { render, inline, escape } from './lib/markdown.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const catalog = JSON.parse(read('dist/components.json'));
const GROUPS = { core: 'Core', brand: 'Brand', forms: 'Forms', navigation: 'Navigation', feedback: 'Feedback', data: 'Data', disclosure: 'Disclosure', overlay: 'Overlay' };
const slug = (name) => name.toLowerCase();
const byGroup = Object.keys(GROUPS).map((g) => [g, catalog.components.filter((c) => c.group === g).sort((a, b) => a.name.localeCompare(b.name))]).filter(([, list]) => list.length);

// ─── Page shell ────────────────────────────────────────────────────────────
function page({ title, description, root, current, main, scripts = '' }) {
  const nav = byGroup.map(([g, list]) => `<li><p class="site-nav__group">${GROUPS[g]}</p><ul>${list.map((c) => `<li><a class="site-nav__link" href="${root}site/components/${slug(c.name)}.html"${c.name === current ? ' aria-current="page"' : ''}>${c.name}</a></li>`).join('')}</ul></li>`).join('');
  return `<!DOCTYPE html>
<!-- GENERATED by scripts/build-site.mjs from dist/components.json and the .prompt.md files — do not edit. -->
<html lang="en" data-rse-theme="auto">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escape(title)}</title>
<meta name="description" content="${escape(description)}">
<link rel="icon" href="${root}assets/favicon.png">
<link rel="stylesheet" href="${root}styles.css">
<link rel="stylesheet" href="${root}site/site.css">
<script src="${root}motion.js"></script>
<script>window.RSE.motion.init();</script>
</head>
<body>
<a class="site-skip" href="#content">Skip to content</a>
<header class="rse-navbar">
  <div class="rse-navbar__inner">
    <a class="site-brand" href="${root}site/index.html">
      <img class="rse-navbar__logo rse-navbar__logo--light" src="${root}assets/logos/wordmark-purple.svg" alt="Rede Sesc de Educação" width="132" height="44">
      <img class="rse-navbar__logo rse-navbar__logo--dark" src="${root}assets/logos/wordmark-white.svg" alt="Rede Sesc de Educação" width="132" height="44">
      <span class="site-brand__label">Design system reference</span>
    </a>
    <nav class="rse-navbar__links" aria-label="Site">
      <a class="rse-navbar__link" href="${root}site/index.html"${current === 'index' ? ' aria-current="page"' : ''}>Components</a>
      <a class="rse-navbar__link" href="${root}docs/tokens.md">Tokens</a>
      <a class="rse-navbar__link" href="${root}docs/integration.md">Integration</a>
    </nav>
    <a class="rse-navbar__cta" href="${root}showcase/index.html">Showcase</a>
  </div>
</header>
<div class="rse-container site-layout">
  <main id="content" class="site-main" tabindex="-1">
${main}
  </main>
  <nav class="site-nav" aria-label="Components">
    <ul>${nav}</ul>
  </nav>
</div>
<footer class="site-footer rse-container">
  <p>${escape(catalog.package)} ${escape(catalog.version)} · generated from <code>dist/components.json</code> · <a href="${root}AGENTS.md">AGENTS.md</a></p>
</footer>
${scripts}
</body>
</html>
`;
}

const vendor = (root) => `<script src="${root}assets/vendor/react.production.min.js"></script>
<script src="${root}assets/vendor/react-dom.production.min.js"></script>
<script src="${root}dist/rse.js"></script>
<script src="${root}showcase/demos.js"></script>
<script src="${root}site/site.js"></script>`;

// ─── Component pages ───────────────────────────────────────────────────────
const tableWrap = (label, inner) => `<div class="site-table" tabindex="0" role="region" aria-label="${escape(label)}"><table>${inner}</table></div>`;
function componentPage(c) {
  const root = '../../';
  const usage = render(read(c.files.usage), { headingOffset: 2, codeLabel: (lang) => `${c.name} ${lang || ''} example`.replace(/\s+/g, ' ').trim() });
  const props = c.props.length ? tableWrap(`${c.name} props`, `<thead><tr><th scope="col">Prop</th><th scope="col">Type</th><th scope="col">Required</th><th scope="col">Notes</th></tr></thead><tbody>${c.props.map((p) => `<tr><th scope="row"><code>${escape(p.name)}</code></th><td>${p.values ? p.values.map((v) => `<code>${escape(v)}</code>`).join(' ') : `<code>${escape(p.type)}</code>`}</td><td>${p.required ? 'yes' : '—'}</td><td>${p.doc ? inline(p.doc) : ''}</td></tr>`).join('')}</tbody>`) : '<p>No props of its own.</p>';
  const extend = c.extends ? `<p class="site-note">Also accepts every attribute of <code>${escape(c.extends)}</code>${c.kind === 'component' ? ', a <code>ref</code> and <code>className</code>' : ''}.</p>` : '';
  const classes = c.classes.blocks.length ? `<dl class="site-classes">
<dt>Blocks</dt><dd>${c.classes.blocks.map((x) => `<code>.${x}</code>`).join(' ')}</dd>
${c.classes.elements.length ? `<dt>Elements</dt><dd>${c.classes.elements.map((x) => `<code>.${x}</code>`).join(' ')}</dd>` : ''}
${c.classes.modifiers.length ? `<dt>Modifiers</dt><dd>${c.classes.modifiers.map((m) => `<code>.${m.class}</code>${m.prop ? ` <span class="site-muted">(${escape(m.prop)})</span>` : ''}`).join(' ')}</dd>` : ''}
</dl>` : '<p>Renders no class contract of its own (generated artwork or a function library).</p>';
  const tokens = c.tokens.length ? `<h2 id="tokens">Component tokens</h2>
<p>Set any of these on <code>:root</code> or an ancestor to re-skin ${c.name} without touching its CSS. Each defaults to a role token, so it follows the theme. Use a role or palette token as the new value, and keep its pairs in <code>scripts/contrast-pairs.mjs</code> passing.</p>
${tableWrap(`${c.name} tokens`, `<thead><tr><th scope="col">Token</th><th scope="col">Default</th><th scope="col">Light</th><th scope="col">Dark</th><th scope="col">Contrast</th></tr></thead><tbody>${c.tokens.map((t) => `<tr><th scope="row"><code>${t.name}</code></th><td><code>${escape(t.ref)}</code></td>${['light', 'dark', 'contrast'].map((m) => `<td><code>${escape(t.values[m])}</code></td>`).join('')}</tr>`).join('')}</tbody>`)}` : '';
  const files = Object.entries(c.files).filter(([, p]) => p).map(([k, p]) => `<li>${k}: <a href="${root}${p}"><code>${p}</code></a></li>`).join('');
  const main = `    <p class="rse-eyebrow">${GROUPS[c.group]}${c.kind !== 'component' ? ` · ${c.kind}` : ''}</p>
    <h1>${c.name}</h1>
    <p class="site-lead">${inline(c.summary)}</p>
    <p class="site-gloss" lang="pt-BR" data-gloss="${c.name}"></p>
    <h2 id="example">Live example</h2>
    <div class="site-demo" lang="pt-BR" data-component="${c.name}"><p class="site-note">The example needs JavaScript; the usage below shows the markup.</p></div>
    <h2 id="usage">Usage</h2>
    <div class="site-prose">${usage}</div>
    <h2 id="props">Props</h2>
    ${props}
    ${extend}
    <h2 id="classes">CSS classes</h2>
    ${classes}
    ${tokens}
    <h2 id="files">Files</h2>
    <ul>${files}</ul>
    <p class="site-note">${c.client ? "Calls a React hook: the source starts with <code>'use client'</code>. " : ''}Import from <code>${escape(catalog.package)}</code>, or read <code>window.RSE.${c.name}</code> after <code>dist/rse.js</code>.</p>`;
  return page({ title: `${c.name} — Rede Sesc de Educação design system`, description: c.summary, root, current: c.name, main, scripts: vendor(root) });
}

// ─── Index ─────────────────────────────────────────────────────────────────
function indexPage() {
  const root = '../';
  const groups = byGroup.map(([g, list]) => `<h2 id="${g}">${GROUPS[g]}</h2>
<ul class="rse-grid site-cards" style="--rse-grid-min: 16rem">${list.map((c) => `<li class="site-card"><a class="site-card__link" href="components/${slug(c.name)}.html">${c.name}</a><p>${inline(c.summary)}</p></li>`).join('')}</ul>`).join('\n');
  const layout = catalog.layout.flatMap((l) => l.classes).filter((x) => x.doc);
  const main = `    <p class="rse-eyebrow">Reference</p>
    <h1>Components</h1>
    <p class="site-lead">${catalog.count} components, each with its live example, usage, props and allowed values, the CSS classes it renders and the tokens that re-skin it. Everything here is generated from <a href="${root}dist/components.json"><code>dist/components.json</code></a>, which tools and agents can read directly.</p>
${groups}
    <h2 id="layout">Layout primitives</h2>
    <p>Plain classes with no React wrapper, from <code>components/layout/layout.css</code>.</p>
    ${tableWrap('Layout primitives', `<thead><tr><th scope="col">Class</th><th scope="col">What it does</th></tr></thead><tbody>${layout.map((x) => `<tr><th scope="row"><code>.${x.class}</code></th><td>${inline(x.doc)}</td></tr>`).join('')}</tbody>`)}`;
  return page({ title: 'Components — Rede Sesc de Educação design system', description: 'Reference for the components of the Rede Sesc de Educação design system.', root, current: 'index', main });
}

// ─── Write ─────────────────────────────────────────────────────────────────
const outputs = new Map([['site/index.html', indexPage()]]);
for (const c of catalog.components) outputs.set(`site/components/${slug(c.name)}.html`, componentPage(c));

let stale = 0;
for (const [path, html] of outputs) {
  const current = existsSync(join(ROOT, path)) ? read(path) : null;
  if (current === html) continue;
  stale++;
  if (checkOnly) { console.log(`${path} is out of date — run \`npm run sync\``); continue; }
  mkdirSync(dirname(join(ROOT, path)), { recursive: true });
  writeFileSync(join(ROOT, path), html);
}
// A page for a component that no longer exists is stale too.
const dir = join(ROOT, 'site/components');
for (const f of existsSync(dir) ? readdirSync(dir) : []) {
  if (outputs.has(`site/components/${f}`)) continue;
  stale++;
  if (checkOnly) console.log(`site/components/${f} has no component — run \`npm run sync\``);
  else rmSync(join(dir, f));
}
if (checkOnly && stale) process.exit(1);
console.log(stale ? `wrote the reference site (${outputs.size} pages)` : `site up to date (${outputs.size} pages)`);
