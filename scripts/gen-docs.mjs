#!/usr/bin/env node
// Generates docs/components.md and docs/tokens.md from the source of truth
// (the .d.ts files and _ds_manifest.json). Never edit those two files by hand.
//
//   node scripts/gen-docs.mjs          # write
//   node scripts/gen-docs.mjs --check  # fail if the committed docs are out of date

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const manifest = JSON.parse(readFileSync(join(ROOT, '_ds_manifest.json'), 'utf8'));
const GROUPS = { core: 'Core', brand: 'Brand', forms: 'Forms', navigation: 'Navigation', feedback: 'Feedback', data: 'Data', disclosure: 'Disclosure', overlay: 'Overlay' };

const propsOf = (dts, name) => {
  const block = dts.match(new RegExp(`export interface ${name}Props \\{([\\s\\S]*?)\\n\\}`));
  if (!block) return [];
  return [...block[1].matchAll(/(?:\/\*\*(.*?)\*\/\s*)?\n?\s*'?([\w-]+)'?(\??):\s*([^;]+);/gs)].map((m) => ({
    doc: (m[1] ?? '').trim(),
    name: m[2],
    required: m[3] !== '?',
    type: m[4].replace(/\s+/g, ' ').trim(),
  }));
};
const summaryOf = (dts, name) => {
  // only the doc comment immediately before the declaration, not everything above it
  const m = dts.match(new RegExp(`/\\*\\*((?:(?!\\*/)[\\s\\S])*)\\*/\\s*export function ${name}\\b`));
  return m ? m[1].replace(/^\s*\*\s?/gm, ' ').replace(/\s+/g, ' ').trim() : '';
};
const cell = (s) => String(s).replace(/\|/g, '\\|');

// ── components.md ──────────────────────────────────────────────────────────
let out = `<!-- generated by scripts/gen-docs.mjs — do not edit by hand -->
# Component reference

${manifest.components.length} components. Every one ships \`.jsx\` (source), \`.d.ts\` (props) and
\`.prompt.md\` (when to use it, with an example) side by side — read the \`.prompt.md\` before
using a component for the first time.

In React, import from \`index.js\`. In a static page, load \`_ds_bundle.js\` and read components
off \`window.${manifest.namespace}\`. See [../AGENTS.md](../AGENTS.md).

`;
const byGroup = {};
for (const c of manifest.components) (byGroup[c.sourcePath.split('/')[1]] ??= []).push(c);
for (const [dir, title] of Object.entries(GROUPS)) {
  const list = (byGroup[dir] ?? []).sort((a, b) => a.name.localeCompare(b.name));
  if (!list.length) continue;
  out += `## ${title}\n\n`;
  for (const c of list) {
    const dts = readFileSync(join(ROOT, c.sourcePath.replace(/\.jsx$/, '.d.ts')), 'utf8');
    const prompt = readFileSync(join(ROOT, c.sourcePath.replace(/\.jsx$/, '.prompt.md')), 'utf8');
    const firstLine = prompt.split('\n').find((l) => l.trim() && !l.startsWith('```'))?.trim() ?? '';
    const props = propsOf(dts, c.name);
    out += `### ${c.name}\n\n${summaryOf(dts, c.name) || firstLine}\n\n`;
    if (props.length) {
      out += `| prop | type | required | notes |\n| --- | --- | --- | --- |\n`;
      for (const p of props) {
        out += `| \`${p.name}\` | \`${cell(p.type)}\` | ${p.required ? 'yes' : '—'} | ${cell(p.doc)} |\n`;
      }
      out += '\n';
    }
    out += `\`${c.sourcePath}\` · [props](../${c.sourcePath.replace(/\.jsx$/, '.d.ts')}) · [usage](../${c.sourcePath.replace(/\.jsx$/, '.prompt.md')})\n\n`;
  }
}

// ── tokens.md ──────────────────────────────────────────────────────────────
const base = manifest.tokens.filter((t) => !t.scope);
const themed = manifest.tokens.filter((t) => t.scope);
const themeNames = [...new Set(themed.map((t) => t.scope))];
let tk = `<!-- generated by scripts/gen-docs.mjs — do not edit by hand -->
# Token reference

${base.length} base tokens across ${new Set(base.map((t) => t.definedIn)).size} files, plus
${themed.length} overrides in ${themeNames.length} themes (${themeNames.join(', ')}).

Rules that matter more than the list itself:

- Never hard-code a colour, size, radius, shadow or duration in a component or page — use \`var(--token)\`.
- A token name means exactly one thing. \`--text-body\` is the body text **colour**; the body text
  **size** is \`--text-body-md\`. \`node scripts/check-ds.mjs\` fails the build if a name is ever
  defined twice with different meanings.
- Brand hex values never change between themes. Themes re-map the *semantic* layer
  (\`--surface-*\`, \`--text-*\`, \`--border-*\`, \`--tint-*\`) only.
- Any new token has to be added to \`tokens/*.css\` **and** registered by running
  \`node scripts/sync-tokens.mjs\`.

`;
for (const file of [...new Set(base.map((t) => t.definedIn))]) {
  tk += `## ${file}\n\n| token | value | kind |\n| --- | --- | --- |\n`;
  for (const t of base.filter((t) => t.definedIn === file)) {
    tk += `| \`${t.name}\` | \`${t.value}\` | ${t.kind} |\n`;
  }
  tk += '\n';
}
for (const scope of themeNames) {
  tk += `## ${scope}\n\n| token | value |\n| --- | --- |\n`;
  for (const t of themed.filter((t) => t.scope === scope)) tk += `| \`${t.name}\` | \`${t.value}\` |\n`;
  tk += '\n';
}

const files = { 'docs/components.md': out, 'docs/tokens.md': tk };
let stale = false;
for (const [p, content] of Object.entries(files)) {
  const full = join(ROOT, p);
  const current = existsSync(full) ? readFileSync(full, 'utf8') : null;
  if (current === content) continue;
  stale = true;
  if (checkOnly) { console.log(`out of date: ${p}`); continue; }
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content);
  console.log(`wrote ${p}`);
}
if (!stale) console.log('docs already up to date');
process.exit(checkOnly && stale ? 1 : 0);
