#!/usr/bin/env node
// Generates docs/components.md and docs/tokens.md from the source of truth
// (the .d.ts files and rse.manifest.json). Never edit those two files by hand.
//
//   node scripts/gen-docs.mjs          # write
//   node scripts/gen-docs.mjs --check  # fail if the committed docs are out of date

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const manifest = JSON.parse(readFileSync(join(ROOT, 'rse.manifest.json'), 'utf8'));
const GROUPS = { core: 'Core', brand: 'Brand', forms: 'Forms', navigation: 'Navigation', feedback: 'Feedback', data: 'Data', disclosure: 'Disclosure', overlay: 'Overlay' };

const propsOf = (dts, name) => {
  const block = dts.match(new RegExp(`export interface ${name}Props \\{([\\s\\S]*?)\\n\\}`));
  if (!block) return [];
  return [...block[1].matchAll(/(?:\/\*\*(.*?)\*\/\s*)?\n?\s*'?([\w-]+)'?(\??):\s*([^;]+);/gs)].map((m) => ({
    doc: (m[1] ?? '').trim(),
    name: m[2],
    required: m[3] !== '?',
    type: m[4].replace(/\s+/g, ' ').trim(),
  }));
};
const summaryOf = (dts, name) => {
  // only the doc comment immediately before the declaration, not everything above it
  const m = dts.match(new RegExp(`/\\*\\*((?:(?!\\*/)[\\s\\S])*)\\*/\\s*export function ${name}\\b`));
  return m ? m[1].replace(/^\s*\*\s?/gm, ' ').replace(/\s+/g, ' ').trim() : '';
};
const cell = (s) => String(s).replace(/\|/g, '\\|');

// ── components.md ──────────────────────────────────────────────────────────
let out = `<!-- generated by scripts/gen-docs.mjs — do not edit by hand -->
# Component reference

${manifest.components.length} components. Every one ships \`.jsx\` (source), \`.d.ts\` (props) and
\`.prompt.md\` (when to use it, with an example) side by side — read the \`.prompt.md\` before
using a component for the first time.

In React, import from \`index.js\`. In a static page, load \`dist/rse.js\` and read components
off \`window.${manifest.namespace}\`. See [../AGENTS.md](../AGENTS.md).

`;
const byGroup = {};
for (const c of manifest.components) (byGroup[c.sourcePath.split('/')[1]] ??= []).push(c);
for (const [dir, title] of Object.entries(GROUPS)) {
  const list = (byGroup[dir] ?? []).sort((a, b) => a.name.localeCompare(b.name));
  if (!list.length) continue;
  out += `## ${title}\n\n`;
  for (const c of list) {
    const dts = readFileSync(join(ROOT, c.sourcePath.replace(/\.jsx$/, '.d.ts')), 'utf8');
    const prompt = readFileSync(join(ROOT, c.sourcePath.replace(/\.jsx$/, '.prompt.md')), 'utf8');
    const firstLine = prompt.split('\n').find((l) => l.trim() && !l.startsWith('```'))?.trim() ?? '';
    const props = propsOf(dts, c.name);
    out += `### ${c.name}\n\n${summaryOf(dts, c.name) || firstLine}\n\n`;
    if (props.length) {
      out += `| prop | type | required | notes |\n| --- | --- | --- | --- |\n`;
      for (const p of props) {
        out += `| \`${p.name}\` | \`${cell(p.type)}\` | ${p.required ? 'yes' : '—'} | ${cell(p.doc)} |\n`;
      }
      out += '\n';
    }
    out += `\`${c.sourcePath}\` · [props](../${c.sourcePath.replace(/\.jsx$/, '.d.ts')}) · [usage](../${c.sourcePath.replace(/\.jsx$/, '.prompt.md')})\n\n`;
  }
}

// ── tokens.md ──────────────────────────────────────────────────────────────
// From dist/tokens.json (scripts/build-tokens.mjs), so every value is already resolved per theme.
const dist = JSON.parse(readFileSync(join(ROOT, 'dist/tokens.json'), 'utf8'));
const names = Object.keys(dist.tokens);
const groupOf = (n) => n.replace(/^--rse-/, '').split('-')[0];
const GROUP_TITLE = {
  brand: 'rse.brand — tier 1, the palette (never themed)', color: 'rse.color — tier 2, colour roles',
  font: 'rse.font', line: 'rse.line-height', letter: 'rse.letter-spacing', space: 'rse.space',
  container: 'rse.container', grid: 'rse.grid', section: 'rse.section-y', header: 'rse.header', hit: 'rse.hit-target',
  focus: 'rse.focus-ring', z: 'rse.z', breakpoint: 'rse.breakpoint — JSON/JS only, not CSS', radius: 'rse.radius',
  shadow: 'rse.shadow', ease: 'rse.ease', duration: 'rse.duration',
};
const cellv = (v) => '`' + String(v).replace(/\|/g, '\\|') + '`';
let tk = `<!-- generated by scripts/gen-docs.mjs from dist/tokens.json — do not edit by hand -->
# Token reference

${names.length} tokens, source \`tokens/src/*.tokens.json\` (W3C DTCG). Values below are resolved;
a value that differs per theme shows all three.

- Never hard-code a colour, size, radius, shadow or duration in a component or page — use \`var(--rse-…)\`.
- Components and pages read **tier 2** (\`--rse-color-*\` and the scales). \`--rse-brand-*\` is the palette:
  read it only for brand artwork and inside the token source.
- To add or change a token, edit \`tokens/src/*.tokens.json\` and run \`npm run sync\`. Never edit
  \`tokens/tokens.css\` or \`dist/\`.
- *derived* = not published by the manual; system work, said out loud.

`;
let current = '';
for (const n of names) {
  const g = groupOf(n);
  const m = dist.tokens[n];
  if (g !== current) {
    current = g;
    tk += `\n## ${GROUP_TITLE[g] ?? g}\n\n| token | light | dark | contrast | notes |\n| --- | --- | --- | --- | --- |\n`;
  }
  const [l, d, c] = ['light', 'dark', 'contrast'].map((mode) => dist.modes[mode][n]);
  const notes = [m.derived && '*derived*', m.cmyk && `C${m.cmyk.c} M${m.cmyk.m} Y${m.cmyk.y} K${m.cmyk.k}`, m.source].filter(Boolean).join(' · ');
  tk += `| \`${n}\` | ${cellv(l)} | ${d === l ? '—' : cellv(d)} | ${c === l ? '—' : cellv(c)} | ${notes} |\n`;
}

const files = { 'docs/components.md': out, 'docs/tokens.md': tk };
let stale = false;
for (const [p, content] of Object.entries(files)) {
  const full = join(ROOT, p);
  const current = existsSync(full) ? readFileSync(full, 'utf8') : null;
  if (current === content) continue;
  stale = true;
  if (checkOnly) { console.log(`out of date: ${p}`); continue; }
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content);
  console.log(`wrote ${p}`);
}
if (!stale) console.log('docs already up to date');
process.exit(checkOnly && stale ? 1 : 0);
