#!/usr/bin/env node
// Builds dist/components.json — the machine-readable component catalog. One record per component
// with everything an agent, a docs site, an MCP server or a design-tool bridge needs, so none of
// them has to read four files per component and re-derive it:
//
//   name, group, kind, summary, files (source/types/usage/css), client (needs 'use client'),
//   element props extend, props (type, required, doc, enumerated values), the CSS classes the
//   component renders (literal and per-value modifiers), the tier 3 tokens it reads (its re-skin
//   points, with each theme's value), and the layout primitives.
//
//   node scripts/build-catalog.mjs          # write
//   node scripts/build-catalog.mjs --check  # exit 1 if stale
//
// Every field is read from a source of truth (manifest, .d.ts, component .js, CSS); nothing here
// is hand-written, so the catalog cannot disagree with the code.

import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { cssContractPath, CONTRACT_ONLY, HOOK_CLASSES, emittedClasses, dynamicModifiers } from './lib/css-contract.mjs';
import { propsOf, extendsOf, summaryOf, literalValues } from './lib/dts.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const OUT = 'dist/components.json';
const read = (p) => readFileSync(join(ROOT, p), 'utf8');
const manifest = JSON.parse(read('rse.manifest.json'));
const pkg = JSON.parse(read('package.json'));

const walk = (dir, out = []) => {
  for (const n of readdirSync(join(ROOT, dir))) {
    const p = join(dir, n);
    statSync(join(ROOT, p)).isDirectory() ? walk(p, out) : out.push(p.split(sep).join('/'));
  }
  return out;
};
const files = walk('components');
const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, '');
const classesIn = (css) => new Set([...stripComments(css).matchAll(/\.(rse-[a-z0-9_-]+)/g)].map((m) => m[1]));
const defined = new Set([...files.filter((f) => f.endsWith('.css')), 'tokens/base-runtime.css'].flatMap((f) => [...classesIn(read(f))]));
const allDts = files.filter((f) => f.endsWith('.d.ts')).map(read).join('\n');
const LIBRARIES = new Set(['MotifEngine']);

// Tier 3 component tokens (tokens/src/component.tokens.json), with their value in each theme.
const tokensDist = JSON.parse(read('dist/tokens.json'));
const flatten = (o, path = []) => Object.entries(o).flatMap(([k, v]) => k.startsWith('$') ? [] : v && typeof v === 'object' && '$value' in v ? [['--' + [...path, k].join('-'), v]] : flatten(v, [...path, k]));
const tier3 = new Map(flatten(JSON.parse(read('tokens/src/component.tokens.json'))));
// The tier 3 tokens a component reads: those in rules, in any component stylesheet, whose selector
// names one of the classes it renders. Attributed rule by rule, so Button.css's button rules do not
// land on IconButton, and the shared .rse-choice rules in Checkbox.css reach Radio and Switch.
const allComponentCss = files.filter((f) => f.endsWith('.css')).map((f) => stripComments(read(f))).join('\n');
const tokensRead = (classes) => {
  const used = new Set();
  for (const [, selector, body] of allComponentCss.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    // A selector applies when every rse-* class in it is one the component renders (so
    // `.rse-switch .rse-choice__box` belongs to Switch, not to Checkbox, which also renders __box).
    const applies = selector.split(',').some((part) => {
      const named = [...part.matchAll(/\.(rse-[a-z0-9_-]+)/g)].map((m) => m[1]);
      return named.length > 0 && named.every((c) => classes.includes(c));
    });
    if (!applies) continue;
    for (const m of body.matchAll(/var\((--rse-[a-z0-9-]+)/g)) if (tier3.has(m[1])) used.add(m[1]);
  }
  return [...used].sort().map((name) => ({
    name,
    ref: tier3.get(name).$value,
    ...(tier3.get(name).$description ? { doc: tier3.get(name).$description } : {}),
    values: Object.fromEntries(Object.keys(tokensDist.modes).map((m) => [m, tokensDist.modes[m][name]])),
  }));
};

const components = manifest.components.map(({ name, sourcePath }) => {
  const src = read(sourcePath);
  const dts = read(sourcePath.replace(/\.js$/, '.d.ts'));
  const css = cssContractPath(ROOT, sourcePath);
  const generated = /GENERATED by scripts\//.test(src);
  const props = propsOf(dts, name).map((p) => {
    const values = literalValues(p.type, allDts);
    return { name: p.name, type: p.type, required: p.required, ...(values ? { values } : {}), ...(p.doc ? { doc: p.doc } : {}) };
  });

  // The classes it renders: literal ones, plus prefix + value for each modifier built from a prop.
  const literal = [...emittedClasses(src)].filter((c) => defined.has(c) || HOOK_CLASSES[c]);
  const modifiers = dynamicModifiers(src).flatMap(({ prefix, prop }) => {
    const p = props.find((x) => x.name === prop);
    return (p?.values ?? []).map((v) => prefix + v).filter((c) => defined.has(c)).map((c) => ({ class: c, prop }));
  });
  const all = [...new Set([...literal, ...modifiers.map((m) => m.class)])].sort();

  return {
    name,
    group: sourcePath.split('/')[1],
    kind: LIBRARIES.has(name) ? 'library' : generated ? 'generated' : 'component',
    summary: summaryOf(dts, name),
    files: {
      source: sourcePath,
      types: sourcePath.replace(/\.js$/, '.d.ts'),
      usage: sourcePath.replace(/\.js$/, '.prompt.md'),
      css,
    },
    client: /^['"]use client['"];/.test(src),
    extends: extendsOf(dts, name),
    props,
    classes: {
      blocks: all.filter((c) => !c.includes('__') && !c.includes('--')),
      elements: all.filter((c) => c.includes('__') && !c.includes('--')),
      modifiers: all.filter((c) => c.includes('--')).map((c) => modifiers.find((m) => m.class === c) ?? { class: c }),
      hooks: all.filter((c) => HOOK_CLASSES[c]),
    },
    tokens: tokensRead(all),
  };
});

// Layout primitives: plain classes, documented in the header comment of their stylesheet.
const layout = CONTRACT_ONLY.map((path) => {
  const css = read(path);
  const header = css.match(/^\/\*([\s\S]*?)\*\//)?.[1] ?? '';
  const classes = [...classesIn(css)].sort();
  const docs = {};
  for (const m of header.matchAll(/^\s*\.(rse-[a-z0-9_-]+)\s+([\s\S]*?)(?=^\s*\.rse-|$(?![\s\S]))/gm)) {
    docs[m[1]] = m[2].replace(/\s+/g, ' ').trim();
  }
  return { css: path, classes: classes.map((c) => ({ class: c, ...(docs[c] ? { doc: docs[c] } : {}) })) };
});

const catalog = {
  $comment: 'GENERATED by scripts/build-catalog.mjs from rse.manifest.json, the .d.ts files, the component sources and their CSS. Do not edit.',
  package: pkg.name,
  version: pkg.version,
  namespace: manifest.namespace,
  import: { react: pkg.name, static: `window.${manifest.namespace}.<Name> after dist/rse.js`, css: `${pkg.name}/styles.css` },
  count: components.length,
  components,
  layout,
};
const out = JSON.stringify(catalog, null, 2) + '\n';
const current = existsSync(join(ROOT, OUT)) ? read(OUT) : null;
if (current === out) { console.log(`components.json up to date (${components.length} components)`); process.exit(0); }
if (checkOnly) { console.log(`${OUT} is out of date — run \`npm run sync\``); process.exit(1); }
mkdirSync(join(ROOT, 'dist'), { recursive: true });
writeFileSync(join(ROOT, OUT), out);
console.log(`wrote ${OUT} (${components.length} components, ${components.reduce((n, c) => n + c.props.length, 0)} props)`);
