#!/usr/bin/env node
/**
 * build-showcase.mjs — generates showcase/showcase-data.js
 *
 * The showcase must open by double-clicking index.html, with no server. Browsers block
 * fetch() from file:// URLs, so brand.json and _ds_manifest.json cannot be read at runtime.
 * This script folds the parts the showcase needs into one plain <script src> file that
 * assigns window.SHOWCASE_DATA.
 *
 * Nothing here is authored by hand: brand.json and _ds_manifest.json are themselves generated
 * from tokens/*.css and the component sources, so the showcase inherits their freshness.
 * Run via `npm run sync`; `npm run check` verifies the output is current with --check.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CONTRAST_PAIRS } from './contrast-pairs.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'showcase', 'showcase-data.js');
const CHECK = process.argv.includes('--check');

const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));
const brand = read('brand.json');
const manifest = read('_ds_manifest.json');
const pkg = read('package.json');

/* ── Components, grouped by the folder they live in ─────────────────────────── */
const GROUP_LABELS = {
  core: 'Essenciais',
  forms: 'Formulários',
  navigation: 'Navegação',
  feedback: 'Retorno ao usuário',
  data: 'Dados',
  disclosure: 'Divulgação progressiva',
  overlay: 'Sobreposição',
  brand: 'Marca',
};

/* docs/components.md is itself generated (gen-docs.mjs) from the .d.ts files, so parsing it
   keeps the summary and the prop table in one place instead of re-deriving them here. */
const parseComponentDocs = () => {
  const md = readFileSync(join(ROOT, 'docs', 'components.md'), 'utf8');
  const out = {};
  for (const block of md.split(/^### /m).slice(1)) {
    const name = block.split('\n')[0].trim();
    const rest = block.slice(block.indexOf('\n') + 1);
    const summary = rest.split(/\n\s*\n/).find((p) => p.trim() && !p.startsWith('|'))?.trim().replace(/\s+/g, ' ') ?? '';
    const props = [];
    for (const row of rest.split('\n')) {
      const m = row.match(/^\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|\s*([^|]*)\|\s*([^|]*)\|/);
      if (m) props.push({ name: m[1], type: m[2].replace(/\\\|/g, '|'), required: m[3].trim() === 'yes', notes: m[4].trim() });
    }
    out[name] = { summary, props };
  }
  return out;
};

const docs = parseComponentDocs();

const components = manifest.components
  .map((c) => {
    const group = c.sourcePath.split('/')[1];
    return {
      name: c.name,
      group,
      groupLabel: GROUP_LABELS[group] ?? group,
      sourcePath: c.sourcePath,
      summary: docs[c.name]?.summary ?? '',
      props: docs[c.name]?.props ?? [],
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name, 'pt-BR'));

/* ── Palette: only the official manual values carry CMYK ────────────────────── */
const palette = brand.palette.map((c) => ({
  token: c.token,
  hex: c.hex,
  cmyk: c.cmyk,
  family: c.family,
  tone: c.tone,
  source: c.source,
}));

/* ── Counts, so the showcase never states a figure it did not derive ────────── */
const countCards = () => {
  let n = 0;
  for (const dir of ['guidelines', 'components']) {
    const walk = (d) => {
      for (const e of readdirSync(join(ROOT, d), { withFileTypes: true })) {
        if (e.isDirectory()) walk(`${d}/${e.name}`);
        else if (e.name.endsWith('.card.html')) n++;
      }
    };
    walk(dir);
  }
  return n;
};

const data = {
  generatedFrom: 'brand.json + _ds_manifest.json — run `npm run sync` to refresh',
  version: pkg.version,
  namespace: manifest.namespace,
  slogan: 'Aprender para a vida acontecer',
  components,
  palette,
  tokens: brand.tokens,
  scales: brand.scales,
  themes: brand.themes,
  assets: brand.assets,
  rules: brand.rules,
  templates: brand.templates,
  contrastPairs: CONTRAST_PAIRS.map(({ label, fg, bg, floor }) => ({ label, fg, bg, floor })),
  counts: {
    components: components.length,
    tokens: Object.keys(brand.tokens).length,
    palette: palette.length,
    themes: Object.keys(brand.themes).length + 1, // + the light default
    templates: brand.templates.length,
    cards: countCards(),
    icons: brand.assets.icons?.count ?? 0,
  },
};

const body = `/* GENERATED by scripts/build-showcase.mjs — do not edit. Run \`npm run sync\`. */\nwindow.SHOWCASE_DATA = ${JSON.stringify(data, null, 2)};\n`;

if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== body) {
    console.error('showcase-data.js is stale — run `npm run sync`');
    process.exit(1);
  }
  console.log('showcase-data.js is current');
} else {
  writeFileSync(OUT, body);
  console.log(`showcase-data.js: ${components.length} components, ${palette.length} palette values, ${data.counts.tokens} tokens`);
}
